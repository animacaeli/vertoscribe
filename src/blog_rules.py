"""内置的 technical-blog-writing 写作规范，不依赖外部技能包安装。"""

from __future__ import annotations

# 5 种文章类型模板
BLOG_TEMPLATES = {
    "教程/How-To": """
## TL;DR
[2-3 句话摘要]

## 前置要求
- 本文假设你已熟悉：[前置知识]

## Step 1：[第一步]
[解释 + 代码 + 输出]

## Step 2：[第二步]
[解释 + 代码 + 输出]

## 完整代码
[GitHub 链接或完整代码块]

## 下一步
[扩展方向]
""",

    "深度解析/Explainer": """
## TL;DR
[2-3 句话摘要 + 关键结论]

## 是什么 + 为什么重要
[概念简介 + 实际价值]

## 心智模型（简化版）
[用类比或简图解释核心原理]

## 详细机制
[深入技术细节]

## 实际案例
[代码演示]

## 权衡与何时不用
[坦诚说明局限性]

## 进一步阅读
[3-5 个相关链接]
""",

    "架构设计/System Design": """
## TL;DR
[解决的问题 + 核心方案]

## 约束与需求
[业务约束 + 技术约束]

## 方案对比
| 方案 | 优点 | 缺点 |
|------|------|------|
| A    | ...  | ...  |
| B（选定）| ...  | ...  |

## 架构详解
[核心设计 + 关键决策]

## 取舍

## 结果与经验
""",

    "基准对比/Benchmark": """
## TL;DR
[对比结论]

## 对比目标
[为什么要对比这些工具]

## 方法论
[测试环境 + 测试方法，确保可复现]

## 结果
[图表 + 数据]

## 分析
[数字意味着什么]

## 推荐
[带限定条件的建议]

## 原始数据
[可复现说明]
""",

    "工具评测/Review": """
## TL;DR
[一句话推荐结论]

## 解决的问题
[为什么需要这个工具]

## 核心功能
[逐一介绍 + 实际体验]

## 优缺点

## 适合谁 / 不适合谁

## 替代品对比

## 总结
""",
}

# 写作规则
WRITING_RULES = {
    "tl_dr": "每篇开头必须有 2-3 句话 TL;DR 摘要",
    "runnable_code": "每个代码块必须完整、标注语言、附预期输出",
    "audience": "开头明确目标读者水平",
    "specific_numbers": '用准确数字代替模糊描述，如"P99 从 800ms 降到 90ms"',
    "admit_tradeoffs": "每个方案都要说明局限性",
    "further_reading": "以 3-5 个相关链接收尾",
}

# 禁用词列表（中英文）
FORBIDDEN_PATTERNS = [
    r"\bsimply\b",
    r"\bjust\b",
    r"\beasily\b",
    r"\bobviously\b",
    r"众所周知",
    r"显而易见",
    r"简单地说",
    r"只需",
    r"很容易",
    r"在当今日新月异的技术世界",
]

# 字数指南
WORD_COUNT_GUIDE = {
    "快速技巧": (500, 800),
    "教程": (1500, 3000),
    "深度解析": (2000, 4000),
    "架构设计": (2000, 3500),
    "基准对比": (1500, 2500),
}


def get_blog_template() -> str:
    """返回所有文章类型模板的拼接，供 LLM prompt 使用。"""
    parts = []
    for name, template in BLOG_TEMPLATES.items():
        parts.append(f"### {name}\n{template}")
    return "\n".join(parts)
