"""内置的 technical-blog-writing 写作规范，不依赖外部技能包安装。"""

from __future__ import annotations

# 5 种文章类型模板
BLOG_TEMPLATES = {
    "教程/How-To": """
## TL;DR
[2-3 句话摘要]

## 前置要求
- 本文假设你已熟悉：[前置知识]

## Step 1：[第一步]
[解释 + 代码 + 输出]

## Step 2：[第二步]
[解释 + 代码 + 输出]

## 完整代码
[GitHub 链接或完整代码块]

## 下一步
[扩展方向]
""",

    "深度解析/Explainer": """
## TL;DR
[2-3 句话摘要 + 关键结论]

## 是什么 + 为什么重要
[概念简介 + 实际价值]

## 心智模型（简化版）
[用类比或简图解释核心原理]

## 详细机制
[深入技术细节]

## 实际案例
[代码演示]

## 权衡与何时不用
[坦诚说明局限性]

## 进一步阅读
[3-5 个相关链接]
""",

    "架构设计/System Design": """
## TL;DR
[解决的问题 + 核心方案]

## 约束与需求
[业务约束 + 技术约束]

## 方案对比
| 方案 | 优点 | 缺点 |
|------|------|------|
| A    | ...  | ...  |
| B（选定）| ...  | ...  |

## 架构详解
[核心设计 + 关键决策]

## 取舍

## 结果与经验
""",

    "基准对比/Benchmark": """
## TL;DR
[对比结论]

## 对比目标
[为什么要对比这些工具]

## 方法论
[测试环境 + 测试方法，确保可复现]

## 结果
[图表 + 数据]

## 分析
[数字意味着什么]

## 推荐
[带限定条件的建议]

## 原始数据
[可复现说明]
""",

    "工具评测/Review": """
## TL;DR
[一句话推荐结论]

## 解决的问题
[为什么需要这个工具]

## 核心功能
[逐一介绍 + 实际体验]

## 优缺点

## 适合谁 / 不适合谁

## 替代品对比

## 总结
""",

    "问答体/Q&A（面试题、答疑类视频）": """
> 先抛问题，再层层拆解。可以有多个小节，每节以问题开头。

## 问题
[用一句话还原原始问题/面试题]

## 多数人的第一反应
[常见答案及其漏洞——先立靶子]

## 更好的答案
[逐层深入，每层回答"为什么还不够"]

## 追问链
[面试官可能的连环追问 + 应对]

## 一句话收束
[把答案压缩成一句可背诵的话]
""",

    "踩坑复盘/Postmortem": """
## 事故现场
[现象描述 + 真实报错/数据，先声夺人]

## 排查过程
[按时间线还原：从第一个怀疑点到定位，允许走进死胡同——那才是真实]

## 根因
[用 mermaid 或示意解释因果链]

## 修复与验证
[修复代码 + 验证方法 + 修复前后的对比数据]

## 反思
[为什么一开始没发现？流程上如何避免再犯]
""",

    "方案对比/VS": """
## 起因
[为什么需要在这几个方案间做选择]

## 候选方案速览
| 维度 | 方案 A | 方案 B |
|------|--------|--------|

## 逐项对决
[每个关键维度一个小节，结合代码/数据实证]

## 判决
[分场景给出结论——几乎没有全场景胜者]
""",
}

# 写作规则的实际约束由 prompts/blog_synthesis.md 承载；
# 此处仅保留 postprocess.py 消费的禁用词列表。

# 禁用词列表（中英文）
FORBIDDEN_PATTERNS = [
    r"\bsimply\b",
    r"\bjust\b",
    r"\beasily\b",
    r"\bobviously\b",
    r"众所周知",
    r"显而易见",
    r"简单地说",
    r"只需",
    r"很容易",
    r"在当今日新月异的技术世界",
    # AI 味高发套话
    r"综上所述",
    r"总而言之",
    r"不言而喻",
    r"毫无疑问",
    r"值得注意的是",
    r"不难发现",
    r"不难看出",
    r"让我们(一起|来)",
    r"在.{0,8}的今天",
    r"随着(科技|技术|互联网)",
    r"赋能",
    r"\bNeedless to say\b",
]


def get_blog_template() -> str:
    """返回所有文章类型模板的拼接，供 LLM prompt 使用。"""
    parts = []
    for name, template in BLOG_TEMPLATES.items():
        parts.append(f"### {name}\n{template}")
    return "\n".join(parts)
